func TestSeekableExtractor_ExtractRecord_FileNotFound(t *testing.T) {
	extCfg := &extract.ExtractRecordMatch{
		FieldMappings: []extract.FieldMapping{
			{OutputField: "name", XPath: "//name", Type: "string"},
		},
	}
	sigCfg := &extract.FileSignature{}

	extractor := NewSeekableExtractor("/nonexistent/file.xml", extCfg, sigCfg, nil)

	workItem := WorkItem{
		RecordNum:   0,
		StartOffset: 0,
		EndOffset:   100,
		SizeBytes:   100,
	}

	result := extractor.ExtractRecord(workItem)

	if result.Error == nil {
		t.Error("Expected error for nonexistent file")
	}
	if result.RecordNum != 0 {
		t.Errorf("Expected RecordNum=0, got %d", result.RecordNum)
	}
}

func TestSeekableExtractor_ExtractRecord_InvalidByteRange(t *testing.T) {
	tmpDir := t.TempDir()
	xmlPath := filepath.Join(tmpDir, "test.xml")

	// Create small XML file
	xmlContent := `<root><item>test</item></root>`
	err := os.WriteFile(xmlPath, []byte(xmlContent), 0600)
	if err != nil {
		t.Fatalf("Failed to create test file: %v", err)
	}

	extCfg := &extract.ExtractRecordMatch{
		FieldMappings: []extract.FieldMapping{
			{OutputField: "name", XPath: "//name", Type: "string"},
		},
	}
	sigCfg := &extract.FileSignature{}

	extractor := NewSeekableExtractor(xmlPath, extCfg, sigCfg, nil)

	// Try to read beyond file size
	workItem := WorkItem{
		RecordNum:   0,
		StartOffset: 0,
		EndOffset:   10000, // Way beyond file size
		SizeBytes:   10000,
	}

	result := extractor.ExtractRecord(workItem)

	if result.Error == nil {
		t.Error("Expected error for invalid byte range")
	}
}

